namespace llvm {

class WDCDAGToDAGISel : public SelectionDAGISel {
public:
  explicit WDCDAGToDAGISel(WDCTargetMachine &TM, CodeGenOptLevel OL)
      : SelectionDAGISel(TM, OL), Subtarget(nullptr) {}

  // Pass Name
//   StringRef getPassName() const override {
//     return "WDC DAG->DAG Pattern Instruction Selection";
//   }

  bool runOnMachineFunction(MachineFunction &MF) override;

protected:

  /// Keep a pointer to the WDCSubtarget around so that we can make the right
  /// decision when generating code for different targets.
  const WDCSubtarget *Subtarget;

private:
  // Include the pieces autogenerated from the target description.
  #include "WDCGenDAGISel.inc"

  /// getTargetMachine - Return a reference to the TargetMachine, casted
  /// to the target-specific type.
  const WDCTargetMachine &getTargetMachine() {
    return static_cast<const WDCTargetMachine &>(TM);
  }

  void Select(SDNode *N) override;

  virtual bool trySelect(SDNode *Node) = 0;

  // Complex Pattern.
  // bool SelectAddr(SDNode *Parent, SDValue N, SDValue &Base, SDValue &Offset);

  // getImm - Return a target constant with the specified value.
  inline SDValue getImm(const SDNode *Node, unsigned Imm) {
    return CurDAG->getTargetConstant(Imm, SDLoc(Node), Node->getValueType(0));
  }

  virtual void processFunctionAfterISel(MachineFunction &MF) = 0;

};


class WDCDAGToDAGISelLegacy : public SelectionDAGISelLegacy {
public:
  static char ID;
  WDCDAGToDAGISelLegacy (std::unique_ptr<SelectionDAGISel> S);
};
}


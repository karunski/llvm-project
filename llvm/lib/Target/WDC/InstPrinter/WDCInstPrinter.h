#ifndef LLVM_LIB_TARGET_WDC_INSTPRINTER_WDCINSTPRINTER_H
#define LLVM_LIB_TARGET_WDC_INSTPRINTER_WDCINSTPRINTER_H

#include "WDCConfig.h"

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {
// These enumeration declarations were orignally in WDCInstrInfo.h but
// had to be moved here to avoid circular dependencies between
// LLVMWDCCodeGen and LLVMWDCAsmPrinter.

class TargetMachine;

class WDCInstPrinter : public MCInstPrinter {
public:
  WDCInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                  const MCRegisterInfo &MRI);
                  
  // Autogenerated by tblgen.
  std::pair<const char *, uint64_t> getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  static const char * getRegisterName(MCRegister Reg);


  void printRegName(raw_ostream &OS, MCRegister RegNo) override;
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

  bool printAliasInstr(const MCInst *MI, uint64_t Address, raw_ostream &OS);
  void printCustomAliasOperand(const MCInst *MI, uint64_t Address,
                               unsigned OpIdx, unsigned PrintMethodIdx,
                               raw_ostream &O);

private:
  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printUnsignedImm(const MCInst *MI, int opNum, raw_ostream &O,
                        unsigned immSize);
  void printOperand(const MCInst *MI, uint64_t /*Address*/, unsigned OpNum,
                    raw_ostream &O) {
    printOperand(MI, OpNum, O);
  }
  void printUnsignedImm16(const MCInst *MI, int opNum, raw_ostream &O);
  void printAbsoluteLong(const MCInst *MI, int opNum, raw_ostream &O);
  void printUnsignedImm8(const MCInst *MI, int opNum, raw_ostream &O);
  void printMemOperand(const MCInst *MI, int opNum, raw_ostream &O);
  void printStackOffset(const MCInst * MI, int opNum, raw_ostream&os);

  void printDirectPageIndirect(const MCInst *MI, int opNum, raw_ostream &os);

  // #if CH >= CH7_1
  void printMemOperandEA(const MCInst *MI, int opNum, raw_ostream &O);
//#endif
};
} // end namespace llvm

#endif